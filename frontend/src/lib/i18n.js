/**
 * Minimal in-house i18n: a flat key -> string dictionary per language, a
 * context exposing t(key) and the current language, and localStorage
 * persistence. No external library — the app has too small a translated
 * surface (global chrome, auth, settings, new-analysis, chat) to justify one.
 *
 * Scope, deliberately: this covers navigation, the language switcher itself,
 * sign-in/sign-up, the new-analysis form, the patient header actions, and
 * shared notices (disclaimer, review banner, chat widget chrome). It does NOT
 * cover clinical output — measurement tables, rationale sentences, quality
 * factor detail, the implant catalogue, Dashboard/History/Research content —
 * because that text is assembled server-side or mixes computed values into
 * English sentences (e.g. "Escalated from {x} · age > 60"); translating it
 * correctly means localizing the backend's string assembly, not just the UI
 * labels, and that's future work. AI-generated text (chat replies, food
 * advice) instead gets a language instruction passed to the model, so those
 * two features do speak the selected language even though this file doesn't
 * contain their words.
 */

